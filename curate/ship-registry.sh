#!/usr/bin/env bash
# registry.toml: one entry per shipped input dir with its tree hash, so the
# user side can verify a share tree and name exactly what a build consumed.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
treehash() { (cd "$1" && find . -type f ! -name .input -print0 | sort -z | xargs -0 sha256sum | sha256sum | cut -d' ' -f1); }
out="$SHARE/registry.toml"
{
  echo "# generated by curate/ship-registry.sh; do not edit"
  echo "schema = 1"
  echo "runtimes_revision = \"$(cat "$SHARE/runtimes/REVISION")\""
  while IFS= read -r stampf; do
    d=$(dirname "$stampf"); rel="${d#$SHARE/}"
    echo; echo "[[input]]"
    echo "path = \"$rel\""
    sed -E 's/^([a-z0-9_]+) = /\1 = /' "$stampf"
    echo "tree_sha256 = \"$(treehash "$d")\""
  done < <(find "$SHARE" -name .input | sort)
} >"$out"
log "registry -> $out ($(grep -c '^\[\[input\]\]' "$out") inputs)"
